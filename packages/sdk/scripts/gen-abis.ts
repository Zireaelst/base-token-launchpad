// Generates src/abis.generated.ts from the audited build artifacts in packages/contracts.
// Run after `bash packages/contracts/script/build-upstream.sh`: `pnpm --filter @launchpad/sdk gen:abis`.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { keccak256 } from "viem";

const root = join(dirname(fileURLToPath(import.meta.url)), "../../contracts/lib");

const artifacts = {
  liquidityLauncherAbi: "liquidity-launcher/out/LiquidityLauncher.sol/LiquidityLauncher.json",
  instantLaunchStrategyAbi: "liquidity-launcher/out/InstantLaunchStrategy.sol/InstantLaunchStrategy.json",
  universalRouterStrategyAbi:
    "liquidity-launcher/out/UniversalRouterStrategy.sol/UniversalRouterStrategy.json",
  feeSplitterAbi: "liquidity-launcher/out/FeeSplitter.sol/FeeSplitter.json",
  beneficiaryVaultAbi: "liquidity-launcher/out/BeneficiaryVault.sol/BeneficiaryVault.json",
  uerc20FactoryAbi: "uerc20-factory/out/UERC20Factory.sol/UERC20Factory.json",
  uerc20Abi: "uerc20-factory/out/UERC20.sol/UERC20.json",
} as const;

const read = (path: string) =>
  JSON.parse(readFileSync(join(root, path), "utf8")) as { abi: unknown; bytecode: { object: `0x${string}` } };

let out =
  "// GENERATED by scripts/gen-abis.ts from the audited build artifacts. Do not edit.\n" +
  "// Sources: liquidity-launcher @ 1c59049, uerc20-factory @ de5bacd.\n\n";

for (const [name, path] of Object.entries(artifacts)) {
  out += `export const ${name} = ${JSON.stringify(read(path).abi)} as const;\n\n`;
}

// UERC20Factory.getUERC20Address hashes `type(UERC20).creationCode`; the factory and the token
// come from the same compile, so the token artifact's bytecode is that creation code.
const uerc20InitCodeHash = keccak256(read(artifacts.uerc20Abi).bytecode.object);
out += `/** keccak256(type(UERC20).creationCode), used to predict token addresses offline. */\n`;
out += `export const UERC20_INIT_CODE_HASH = "${uerc20InitCodeHash}" as const;\n`;

writeFileSync(join(dirname(fileURLToPath(import.meta.url)), "../src/abis.generated.ts"), out);
console.log("wrote src/abis.generated.ts");
